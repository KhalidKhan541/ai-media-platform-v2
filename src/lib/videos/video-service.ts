export class VideoService {
  private videoModel: IVideoModel;
  private processingJobs: Map<string, ProcessingJob> = new Map();

  constructor() {
    this.videoModel = (mongoose.models.Video as IVideoModel) ||
      mongoose.model<IVideo, IVideoModel>("Video", VideoSchema);

    if (!mongoose.models.ProcessingJob) {
      mongoose.model<ProcessingJob>("ProcessingJob", ProcessingJobSchema);
    }
  }

  // -- CRUD ------------------------------------------------------------------

  async createVideo(input: CreateVideoInput, channelId: string): Promise<IVideo> {
    const parsed = CreateVideoSchema.parse({ ...input, channelId });
    const video = new this.videoModel({
      ...parsed,
      channelId,
      status: "draft",
    });
    return video.save();
  }

  async getVideo(videoId: string): Promise<IVideo | null> {
    return this.videoModel.findByVideoId(videoId);
  }

  async updateVideo(
    videoId: string,
    input: UpdateVideoInput,
    requesterChannelId: string
  ): Promise<IVideo | null> {
    const parsed = UpdateVideoSchema.parse(input);
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    if (video.channelId !== requesterChannelId) {
      throw new Error("Unauthorized: not the channel owner");
    }
    Object.assign(video, parsed);
    return video.save();
  }

  async deleteVideo(
    videoId: string,
    requesterChannelId: string
  ): Promise<boolean> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return false;
    if (video.channelId !== requesterChannelId) {
      throw new Error("Unauthorized: not the channel owner");
    }
    await this.videoModel.deleteOne({ videoId });
    return true;
  }

  async archiveVideo(
    videoId: string,
    requesterChannelId: string
  ): Promise<IVideo | null> {
    return this.updateVideo(
      videoId,
      { status: "archived" },
      requesterChannelId
    );
  }

  // -- Publishing ------------------------------------------------------------

  async publishVideo(videoId: string): Promise<IVideo> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) throw new Error("Video not found");
    if (video.status !== "ready") {
      throw new Error("Video must be ready before publishing");
    }
    video.status = "ready";
    video.publishedAt = new Date();
    return video.save();
  }

  async schedulePublish(videoId: string, scheduledAt: Date): Promise<IVideo> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) throw new Error("Video not found");
    if (scheduledAt <= new Date()) {
      throw new Error("Scheduled time must be in the future");
    }
    video.scheduledPublishAt = scheduledAt;
    return video.save();
  }

  async processScheduledPublishes(): Promise<IVideo[]> {
    const now = new Date();
    const videos = await this.videoModel.find({
      status: "ready",
      scheduledPublishAt: { $lte: now },
      publishedAt: null,
    });

    const published: IVideo[] = [];
    for (const video of videos) {
      video.publishedAt = now;
      video.scheduledPublishAt = null;
      await video.save();
      published.push(video);
    }
    return published;
  }

  // -- Processing ------------------------------------------------------------

  async startProcessing(videoId: string): Promise<IVideo> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) throw new Error("Video not found");
    video.status = "processing";
    await video.save();

    await this.createProcessingJob(videoId, "transcode");
    await this.createProcessingJob(videoId, "thumbnail");
    return video;
  }

  async createProcessingJob(
    videoId: string,
    type: ProcessingJob["type"]
  ): Promise<ProcessingJob> {
    const job: ProcessingJob = {
      jobId: uuidv4(),
      videoId,
      type,
      status: "queued",
      progress: 0,
      startedAt: null,
      completedAt: null,
      createdAt: new Date(),
    };
    this.processingJobs.set(job.jobId, job);

    const JobModel = mongoose.model<ProcessingJob>("ProcessingJob");
    await new JobModel(job).save();
    return job;
  }

  async updateProcessingProgress(
    jobId: string,
    progress: number
  ): Promise<ProcessingJob | null> {
    const job = this.processingJobs.get(jobId);
    if (!job) return null;
    job.progress = Math.min(100, Math.max(0, progress));
    if (job.status === "queued" && progress > 0) {
      job.status = "processing";
      job.startedAt = new Date();
    }
    return job;
  }

  async completeProcessingJob(
    jobId: string,
    result?: Record<string, unknown>
  ): Promise<ProcessingJob | null> {
    const job = this.processingJobs.get(jobId);
    if (!job) return null;
    job.status = "completed";
    job.progress = 100;
    job.completedAt = new Date();
    if (result) job.result = result;

    const allDone = Array.from(this.processingJobs.values())
      .filter((j) => j.videoId === job.videoId)
      .every((j) => j.status === "completed" || j.status === "failed");

    if (allDone) {
      const video = await this.videoModel.findByVideoId(job.videoId);
      if (video) {
        const anyFailed = Array.from(this.processingJobs.values())
          .filter((j) => j.videoId === job.videoId)
          .some((j) => j.status === "failed");
        video.status = anyFailed ? "failed" : "ready";
        await video.save();
      }
    }
    return job;
  }

  async failProcessingJob(
    jobId: string,
    error: string
  ): Promise<ProcessingJob | null> {
    const job = this.processingJobs.get(jobId);
    if (!job) return null;
    job.status = "failed";
    job.error = error;
    job.completedAt = new Date();
    return job;
  }

  async getProcessingJobs(videoId: string): Promise<ProcessingJob[]> {
    return Array.from(this.processingJobs.values()).filter(
      (j) => j.videoId === videoId
    );
  }

  // -- Subtitles -------------------------------------------------------------

  async addSubtitle(
    videoId: string,
    subtitle: Omit<SubtitleEntry, "id">
  ): Promise<IVideo | null> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    const entry: SubtitleEntry = { ...subtitle, id: uuidv4() };
    video.subtitles.push(entry as never);
    return video.save();
  }

  async removeSubtitle(
    videoId: string,
    subtitleId: string
  ): Promise<IVideo | null> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    video.subtitles = video.subtitles.filter(
      (s) => s.id !== subtitleId
    ) as never;
    return video.save();
  }

  async getSubtitles(videoId: string): Promise<SubtitleEntry[]> {
    const video = await this.videoModel.findByVideoId(videoId);
    return video?.subtitles ?? [];
  }

  async generateAISubtitles(
    videoId: string,
    language: string
  ): Promise<SubtitleEntry> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) throw new Error("Video not found");
    if (!video.metadata) throw new Error("Video has no metadata");

    const subtitle: SubtitleEntry = {
      id: uuidv4(),
      language,
      label: `${language} (AI Generated)`,
      url: "",
      isAutoGenerated: true,
      segments: [],
    };

    video.subtitles.push(subtitle as never);
    await video.save();

    await this.createProcessingJob(videoId, "subtitle");
    return subtitle;
  }

  // -- Analytics -------------------------------------------------------------

  async recordView(videoId: string, seconds: number, percentage: number) {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) throw new Error("Video not found");
    await video.incrementViews();
    await video.addWatchTime(seconds, percentage);
  }

  async getAnalytics(videoId: string) {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) throw new Error("Video not found");

    const jobs = await this.getProcessingJobs(videoId);
    return {
      views: video.viewCount,
      likes: video.likeCount,
      dislikes: video.dislikeCount,
      comments: video.commentCount,
      shares: video.shareCount,
      watchTimeHours: video.watchTimeSeconds / 3600,
      averageWatchPercentage: video.averageWatchPercentage,
      processingJobs: jobs.length,
      completedJobs: jobs.filter((j) => j.status === "completed").length,
    };
  }

  // -- Search & Browse -------------------------------------------------------

  async listVideos(query: VideoQueryInput): Promise<VideoListResult> {
    const parsed = VideoQuerySchema.parse(query);
    const filter: Record<string, unknown> = {};

    if (parsed.channelId) filter.channelId = parsed.channelId;
    if (parsed.category) filter.category = parsed.category;
    if (parsed.visibility) filter.visibility = parsed.visibility;
    if (parsed.status) filter.status = parsed.status;
    else filter.status = { $in: ["ready", "processing"] };
    if (parsed.tags?.length) filter.tags = { $in: parsed.tags };
    if (parsed.search) {
      filter.$text = { $search: parsed.search };
    }

    const sortMap: Record<string, Record<string, 1 | -1>> = {
      newest: { publishedAt: -1 },
      oldest: { publishedAt: 1 },
      popular: { viewCount: -1 },
      trending: { likeCount: -1 },
      duration: { "metadata.duration": -1 },
    };

    const total = await this.videoModel.countDocuments(filter);
    const skip = (parsed.page - 1) * parsed.limit;
    const videos = await this.videoModel
      .find(filter)
      .sort(sortMap[parsed.sort] ?? sortMap.newest)
      .skip(skip)
      .limit(parsed.limit);

    const totalPages = Math.ceil(total / parsed.limit);

    return {
      videos,
      total,
      page: parsed.page,
      limit: parsed.limit,
      totalPages,
      hasNext: parsed.page < totalPages,
      hasPrev: parsed.page > 1,
    };
  }

  async getChannelVideos(channelId: string, limit = 20) {
    return this.videoModel.findByChannel(channelId, limit);
  }

  async getTrending(limit = 20, category?: string) {
    return this.videoModel.findTrending({ limit, category });
  }

  async getPopular(limit = 20, days?: number) {
    return this.videoModel.findPopular({ limit, days });
  }

  async searchVideos(query: string, limit = 20) {
    return this.videoModel.searchByTitle(query, limit);
  }

  // -- Metadata & AI ---------------------------------------------------------

  async updateMetadata(
    videoId: string,
    metadata: Partial<VideoMetadata>
  ): Promise<IVideo | null> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    video.metadata = { ...video.metadata, ...metadata } as VideoMetadata;
    return video.save();
  }

  async setThumbnail(videoId: string, thumbnailUrl: string): Promise<IVideo | null> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    video.thumbnailUrl = thumbnailUrl;
    return video.save();
  }

  async generateAITags(videoId: string, tags: string[]): Promise<IVideo | null> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    video.aiTags = tags;
    return video.save();
  }

  async markAsAIGenerated(videoId: string): Promise<IVideo | null> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (!video) return null;
    video.aiGenerated = true;
    return video.save();
  }

  // -- Utilities -------------------------------------------------------------

  async countByChannel(channelId: string): Promise<number> {
    return this.videoModel.countDocuments({ channelId });
  }

  async countByStatus(status: VideoStatus): Promise<number> {
    return this.videoModel.countDocuments({ status });
  }

  async getRecentVideos(limit = 10): Promise<IVideo[]> {
    return this.videoModel
      .find({ status: "ready", visibility: "public" })
      .sort({ publishedAt: -1 })
      .limit(limit);
  }

  async incrementCommentCount(videoId: string): Promise<void> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (video) await video.incrementComments();
  }

  async decrementCommentCount(videoId: string): Promise<void> {
    const video = await this.videoModel.findByVideoId(videoId);
    if (video) await video.decrementComments();
  }
}

export default VideoService;
