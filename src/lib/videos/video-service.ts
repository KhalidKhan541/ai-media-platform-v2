VideoSchema.methods.incrementViews = function (count = 1) {
  this.viewCount += count;
  return this.save();
};

VideoSchema.methods.incrementLikes = function () {
  this.likeCount += 1;
  return this.save();
};

VideoSchema.methods.decrementLikes = function () {
  this.likeCount = Math.max(0, this.likeCount - 1);
  return this.save();
};

VideoSchema.methods.incrementDislikes = function () {
  this.dislikeCount += 1;
  return this.save();
};

VideoSchema.methods.decrementDislikes = function () {
  this.dislikeCount = Math.max(0, this.dislikeCount - 1);
  return this.save();
};

VideoSchema.methods.incrementComments = function () {
  this.commentCount += 1;
  return this.save();
};

VideoSchema.methods.decrementComments = function () {
  this.commentCount = Math.max(0, this.commentCount - 1);
  return this.save();
};

VideoSchema.methods.incrementShares = function () {
  this.shareCount += 1;
  return this.save();
};

VideoSchema.methods.addWatchTime = function (
  seconds: number,
  watchPercentage: number
) {
  this.watchTimeSeconds += seconds;
  const totalViews = this.viewCount || 1;
  this.averageWatchPercentage =
    (this.averageWatchPercentage * (totalViews - 1) + watchPercentage) /
    totalViews;
  return this.save();
};

// ---------------------------------------------------------------------------
// Static Methods
// ---------------------------------------------------------------------------

VideoSchema.statics.findByVideoId = function (videoId: string) {
  return this.findOne({ videoId });
};

VideoSchema.statics.findTrending = function (options: {
  limit: number;
  category?: string;
}) {
  const cutoff = new Date(Date.now() - 7 * 24 * 60 * 60 * 1000);
  const match: Record<string, unknown> = {
    status: "ready",
    visibility: "public",
    publishedAt: { $gte: cutoff },
  };
  if (options.category) match.category = options.category;

  return this.aggregate([
    { $match: match },
    {
      $addFields: {
        trendingScore: {
          $add: [
            { $multiply: ["$viewCount", 0.4] },
            { $multiply: ["$likeCount", 0.3] },
            { $multiply: ["$commentCount", 0.2] },
            { $multiply: ["$shareCount", 0.1] },
          ],
        },
      },
    },
    { $sort: { trendingScore: -1 } },
    { $limit: options.limit },
  ]);
};

VideoSchema.statics.findPopular = function (options: {
  limit: number;
  days?: number;
}) {
  const days = options.days || 30;
  const cutoff = new Date(Date.now() - days * 24 * 60 * 60 * 1000);
  return this.find({
    status: "ready",
    visibility: "public",
    publishedAt: { $gte: cutoff },
  })
    .sort({ viewCount: -1 })
    .limit(options.limit);
};

VideoSchema.statics.findByChannel = function (
  channelId: string,
  limit = 20
) {
  return this.find({ channelId, status: { $ne: "archived" } })
    .sort({ publishedAt: -1 })
    .limit(limit);
};

VideoSchema.statics.searchByTitle = function (query: string, limit = 20) {
  return this.find(
    { $text: { $search: query }, status: "ready", visibility: "public" },
    { score: { $meta: "textScore" } }
  )
    .sort({ score: { $meta: "textScore" } })
    .limit(limit);
};

