import mongoose, { Schema, Document, Model } from "mongoose";
import { z } from "zod";
import { v4 as uuidv4 } from "uuid";

// ---------------------------------------------------------------------------
// Zod Schemas
// ---------------------------------------------------------------------------

export const VideoMetadataSchema = z.object({
  duration: z.number().min(0),
  width: z.number().int().positive(),
  height: z.number().int().positive(),
  codec: z.string(),
  bitrate: z.number().positive(),
  fps: z.number().positive(),
  format: z.string(),
  size: z.number().positive(),
  thumbnailUrl: z.string().url(),
  hlsUrl: z.string().url().optional(),
  dashUrl: z.string().url().optional(),
  mp4Url: z.string().url().optional(),
});

export const SubtitleEntrySchema = z.object({
  id: z.string().uuid(),
  language: z.string().min(2).max(10),
  label: z.string().min(1),
  url: z.string().url(),
  isAutoGenerated: z.boolean().default(false),
  segments: z
    .array(
      z.object({
        start: z.number().min(0),
        end: z.number().min(0),
        text: z.string(),
      })
    )
    .optional(),
});

export const CreateVideoSchema = z.object({
  title: z.string().min(1).max(300),
  description: z.string().max(5000).optional(),
  channelId: z.string(),
  tags: z.array(z.string().max(50)).max(30).default([]),
  category: z.enum([
    "education",
    "entertainment",
    "gaming",
    "music",
    "news",
    "sports",
    "tech",
    "vlog",
    "other",
  ]),
  visibility: z.enum(["public", "unlisted", "private"]).default("public"),
  allowComments: z.boolean().default(true),
  allowRatings: z.boolean().default(true),
  ageRestricted: z.boolean().default(false),
  scheduledPublishAt: z.date().optional(),
});

export const UpdateVideoSchema = CreateVideoSchema.partial().extend({
  status: z.enum(["draft", "processing", "ready", "failed", "archived"]).optional(),
});

export const VideoQuerySchema = z.object({
  page: z.coerce.number().int().positive().default(1),
  limit: z.coerce.number().int().min(1).max(50).default(20),
  sort: z
    .enum(["newest", "oldest", "popular", "trending", "duration"])
    .default("newest"),
  category: z.string().optional(),
  tags: z.array(z.string()).optional(),
  channelId: z.string().optional(),
  visibility: z.enum(["public", "unlisted", "private"]).optional(),
  search: z.string().max(200).optional(),
});

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type VideoMetadata = z.infer<typeof VideoMetadataSchema>;
export type SubtitleEntry = z.infer<typeof SubtitleEntrySchema>;
export type CreateVideoInput = z.infer<typeof CreateVideoSchema>;
export type UpdateVideoInput = z.infer<typeof UpdateVideoSchema>;
export type VideoQueryInput = z.infer<typeof VideoQuerySchema>;

export type VideoStatus =
  | "draft"
  | "uploading"
  | "processing"
  | "ready"
  | "failed"
  | "archived";

export interface IVideo extends Document {
  _id: string;
  videoId: string;
  title: string;
  description: string;
  channelId: string;
  tags: string[];
  category: string;
  visibility: "public" | "unlisted" | "private";
  status: VideoStatus;
  metadata: VideoMetadata | null;
  subtitles: SubtitleEntry[];
  thumbnailUrl: string;
  allowComments: boolean;
  allowRatings: boolean;
  ageRestricted: boolean;
  viewCount: number;
  likeCount: number;
  dislikeCount: number;
  commentCount: number;
  shareCount: number;
  watchTimeSeconds: number;
  averageWatchPercentage: number;
  scheduledPublishAt: Date | null;
  publishedAt: Date | null;
  aiGenerated: boolean;
  aiTags: string[];
  createdAt: Date;
  updatedAt: Date;

  incrementViews(count?: number): Promise<IVideo>;
  incrementLikes(): Promise<IVideo>;
  decrementLikes(): Promise<IVideo>;
  incrementDislikes(): Promise<IVideo>;
  decrementDislikes(): Promise<IVideo>;
  incrementComments(): Promise<IVideo>;
  decrementComments(): Promise<IVideo>;
  incrementShares(): Promise<IVideo>;
  addWatchTime(seconds: number, watchPercentage: number): Promise<IVideo>;
}

export interface IVideoModel extends Model<IVideo> {
  findByVideoId(videoId: string): Promise<IVideo | null>;
  findTrending(options: { limit: number; category?: string }): Promise<IVideo[]>;
  findPopular(options: { limit: number; days?: number }): Promise<IVideo[]>;
  findByChannel(channelId: string, limit?: number): Promise<IVideo[]>;
  searchByTitle(query: string, limit?: number): Promise<IVideo[]>;
}

export interface VideoListResult {
  videos: IVideo[];
  total: number;
  page: number;
  limit: number;
  totalPages: number;
  hasNext: boolean;
  hasPrev: boolean;
}

export interface ProcessingJob {
  jobId: string;
  videoId: string;
  type: "transcode" | "thumbnail" | "subtitle" | "ai-analysis";
  status: "queued" | "processing" | "completed" | "failed";
  progress: number;
  result?: Record<string, unknown>;
  error?: string;
  startedAt: Date | null;
  completedAt: Date | null;
  createdAt: Date;
}

